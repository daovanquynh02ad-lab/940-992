function initBlitzBlock() {
    if (state.blitzTimer) clearInterval(state.blitzTimer);
    state.blitzTime = 60;
    state.blitzShowRubric = false;
    state.blitzCheckedPoints = {};
    const b = state.playableBlocks[state.currentIndex];
    
    // Голосовая диктовка вопроса (как преподша на коллоквиуме)
    try {
        window.speechSynthesis.cancel();
        const u = new SpeechSynthesisUtterance(`Вопрос: ${b.title}. Время пошло, одна минута.`);
        u.lang = 'ru-RU';
        u.rate = 1.05;
        window.speechSynthesis.speak(u);
    } catch(e) {}

    state.blitzTimer = setInterval(() => {
        state.blitzTime--;
        const el = document.getElementById('blitz-sec');
        const bar = document.getElementById('blitz-bar');
        if (el) el.innerText = `${state.blitzTime}с`;
        if (bar) bar.style.width = `${(state.blitzTime / 60) * 100}%`;
        if (state.blitzTime === 10) haptic('warning');
        if (state.blitzTime <= 0) {
            clearInterval(state.blitzTimer);
            haptic('error');
            state.blitzShowRubric = true;
            render();
        }
    }, 1000);
}

function finishBlitzEarly() {
    haptic('medium');
    if (state.blitzTimer) clearInterval(state.blitzTimer);
    state.blitzShowRubric = true;
    render();
}

function toggleBlitzCheck(idx) {
    haptic('light');
    state.blitzCheckedPoints[idx] = !state.blitzCheckedPoints[idx];
    const b = state.playableBlocks[state.currentIndex];
    const hit = Object.values(state.blitzCheckedPoints).filter(Boolean).length;
    state.userProgress[b.id] = { status: hit >= Math.ceil(b.points.length * 0.75) ? 'correct' : 'wrong' };
    saveProgress();
    render();
}

