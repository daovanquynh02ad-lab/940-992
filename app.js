function initTypeBlock() {
    const b = state.playableBlocks[state.currentIndex];
    if (!b) return;
    const tokens = [];
    b.points.forEach((pt, pIdx) => {
        if (state.typeHardcore) {
            // Хардкор: каждое слово от 3 букв становится мишенью
            const clean = pt.replace(/\{([^}]+)\}/g, '$1');
            clean.split(/(\s+)/).forEach(part => {
                const m = part.match(/^([^а-яА-ЯёЁa-zA-Z0-9]*)([а-яА-ЯёЁa-zA-Z]{3,})(.*)$/);
                if (m) {
                    tokens.push({ isTarget: true, prefix: m[1], word: m[2], suffix: m[3], first: m[2][0].toLowerCase().replace('ё','е'), done: false });
                } else {
                    tokens.push({ isTarget: false, text: part });
                }
            });
        } else {
            // Обычный: только размеченные {ключевые слова}
            const parts = pt.split(/(\{[^}]+\})/g);
            parts.forEach(part => {
                if (part.startsWith('{') && part.endsWith('}')) {
                    const w = part.slice(1, -1);
                    tokens.push({ isTarget: true, prefix: '', word: w, suffix: '', first: w[0].toLowerCase().replace('ё','е'), done: false });
                } else {
                    tokens.push({ isTarget: false, text: part });
                }
            });
        }
        if (pIdx < b.points.length - 1) tokens.push({ isTarget: false, text: '\n\n' });
    });
    state.typeWords = tokens;
    state.typeCursor = tokens.findIndex(t => t.isTarget);
    state.typeError = false;
}

function handleKeyPress(char) {
    if (state.typeCursor === -1) return;
    const target = state.typeWords[state.typeCursor];
    if (!target) return;

    const normChar = char.toLowerCase().replace('ё','е');
    const normTarget = target.first.toLowerCase().replace('ё','е');

    if (normChar === normTarget || (/\d/.test(normTarget) && char === '123')) {
        haptic('light');
        target.done = true;
        state.typeError = false;
        const nextIdx = state.typeWords.findIndex((t, i) => i > state.typeCursor && t.isTarget && !t.done);
        state.typeCursor = nextIdx;
        if (nextIdx === -1) {
            haptic('success');
            const b = state.playableBlocks[state.currentIndex];
            state.userProgress[b.id] = { status: 'correct' };
            saveProgress();
        }
        render();
    } else {
        haptic('error');
        state.typeError = true;
        render();
    }
}

function skipCurrentWord() {
    if (state.typeCursor === -1) return;
    haptic('warning');
    const b = state.playableBlocks[state.currentIndex];
    state.userProgress[b.id] = { status: 'wrong' };
    saveProgress();
    state.typeWords[state.typeCursor].done = true;
    state.typeCursor = state.typeWords.findIndex((t, i) => i > state.typeCursor && t.isTarget && !t.done);
    render();
}

// Слушаем также физическую клавиатуру (для ноутбука)
window.addEventListener('keydown', (e) => {
    if ((state.view === 'type' || state.view === 'mistakes') && e.key && e.key.length === 1) {
        handleKeyPress(e.key);
    }
});

