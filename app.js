// Форматирование текста для Умного Конспекта
function formatLearnPoint(pt) {
    if (state.learnMaskMode === 'full') {
        return pt.replace(/\{([^}]+)\}/g, '<span class="kw-gold">$1</span>');
    } else if (state.learnMaskMode === 'cloze') {
        return pt.replace(/\{([^}]+)\}/g, `<span class="kw-hidden" onclick="haptic('light');this.className='kw-gold'">$1</span>`);
    } else {
        // Матрица первых букв: каждое слово 3+ букв скрывается до первой буквы
        const clean = pt.replace(/\{([^}]+)\}/g, '$1');
        return clean.replace(/([а-яА-ЯёЁa-zA-Z]{3,})/g, (w) => {
            const mask = w[0] + '·'.repeat(Math.min(w.length - 1, 3));
            return `<span class="w-first" data-full="${w}" data-mask="${mask}" onclick="haptic('light');this.innerText=this.innerText===this.dataset.full?this.dataset.mask:this.dataset.full">${mask}</span>`;
        });
    }
}

