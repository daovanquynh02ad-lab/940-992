function startMode(mode) {
    haptic('medium');
    let pool = RAW_BLOCKS.filter(b => state.selectedTopics.includes(b.topic));
    if (mode === 'mistakes') {
        pool = RAW_BLOCKS.filter(b => state.userProgress[b.id]?.status === 'wrong');
    }
    if (!pool.length) {
        alert(mode === 'mistakes' ? "Ошибок пока нет! Пройди Печать или Блиц." : "Выбери хотя бы одну тему в фильтре!");
        return;
    }
    state.playableBlocks = pool;
    state.currentIndex = 0;
    state.view = mode;

    if (mode === 'type' || mode === 'mistakes') initTypeBlock();
    if (mode === 'builder') initBuilderBlock();
    if (mode === 'blitz') initBlitzBlock();
    render();
}

